        BIRTHDATE,
        DATEDIFF(YEAR,BIRTHDATE,GETDATE()) AS AGE_YEAR,
         DATEDIFF(MONTH,BIRTHDATE,GETDATE()) AS AGE_MONTHS,
          DATEDIFF(DAY,BIRTHDATE,GETDATE()) AS AGE_DAYS
        FROM SALES.Employees
       ---- FIND THE AVERAGE SHIPPIND DAYS IN A MONTH---

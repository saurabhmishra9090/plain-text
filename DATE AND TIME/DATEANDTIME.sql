--DATEADD FUNCTION -----

SELECT 
      ORDERID ,
      ORDERDATE,
      DATEADD(YEAR,2,ORDERDATE),
      DATEADD(MONTH,3,ORDERDATE),
      DATEADD(DAY,-3,ORDERDATE) AS THREE_DAYS_EARLIER
FROM SALES.ORDERS
  

